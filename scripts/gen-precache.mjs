/* ============================================================
   Generates hub/sw-manifest.js after a build, and re-stamps hub/sw.js itself.

   Asset filenames are content-hashed, so the service worker cannot know them
   ahead of time. Without an explicit list the worker only caches what happens
   to miss the browser's HTTP cache — which means offline support works or
   fails by luck. This writes the exact list, plus a version stamp derived from
   it so a new build automatically evicts the previous caches.

   The version used to be derived from the /trading dist URL *list* alone,
   which meant editing the hub's own index.html/css/js — content that keeps
   the same filenames — never changed the version at all. Worse, the version
   only ever lived in sw-manifest.js, which sw.js pulls in via importScripts().
   Browsers decide whether to install a new service worker by byte-comparing
   the *registered* script only; changes inside an importScripts() file are
   invisible to that check. Combined, those two bugs meant a real content
   change could ship to the server and still never reach a phone that had
   already installed the service worker once — the exact failure mode behind
   a run of "it's not showing my latest change" reports this session. Both are
   fixed here: the version now hashes real file bytes (hub shell + trading
   dist), and that version is stamped directly into sw.js's own source, so the
   registered script's bytes genuinely change whenever anything does.
   ============================================================ */

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const DIST = path.join(ROOT, 'web', 'dist');
const HUB = path.join(ROOT, 'hub');
const MANIFEST_OUT = path.join(HUB, 'sw-manifest.js');
const SW_FILE = path.join(HUB, 'sw.js');

/** Fonts are large and lazily needed — the shell must stay quick to install. */
const SKIP = /\.(map|woff)$/;

/**
 * iCloud conflict copies — "asset-Bx7f2 3.woff2" — appear in dist when the
 * project lives on a synced Desktop and a build lands mid-sync. They are junk,
 * nothing references them, and precaching them is not merely wasteful: a
 * service worker install fails wholesale if any single addAll() entry 404s, so
 * one stale copy that iCloud later removes takes offline mode down with it.
 */
const ICLOUD_CONFLICT = / \d+\.[a-z0-9]+$/i;

const HUB_SHELL = [
  '/',
  '/index.html',
  '/css/style.css',
  '/js/main.js',
  '/js/shader.js',
  '/js/ui.js',
  '/manifest.json',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/apple-touch-icon.png',
];

/** HUB_SHELL entries, mapped to the real file this build should hash — '/' and
 *  the directory-style '/trading/' URL aren't real paths on disk. */
function hubShellFile(url) {
  if (url === '/') return path.join(HUB, 'index.html');
  return path.join(HUB, url);
}

async function walk(dir, rel = '') {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const childRel = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...(await walk(path.join(dir, entry.name), childRel)));
    else if (!SKIP.test(entry.name) && !ICLOUD_CONFLICT.test(entry.name))
      out.push(`/trading/${childRel}`);
  }
  return out;
}

const distUrls = await walk(DIST);
// index.html is reached as /trading/ — precache the directory URL the app uses.
const urls = [...HUB_SHELL, '/trading/', ...distUrls.filter((u) => u !== '/trading/index.html')];

// Content-hashed dist filenames already change when trading app content does,
// so the URL list alone is enough there. The hub's own shell keeps fixed
// filenames, so its actual bytes have to go into the hash directly, or an
// edit with no filename change would produce the exact same version.
const hash = createHash('sha1');
hash.update(urls.join('|'));
for (const url of HUB_SHELL) {
  try {
    hash.update(await readFile(hubShellFile(url)));
  } catch {
    /* missing shell file — the URL list hash still moves if this changes later */
  }
}
const version = `mc-${hash.digest('hex').slice(0, 10)}`;

await writeFile(
  MANIFEST_OUT,
  `/* generated by scripts/gen-precache.mjs — do not edit */\n` +
    `self.__MC_VERSION = ${JSON.stringify(version)};\n` +
    `self.__MC_PRECACHE = ${JSON.stringify(urls, null, 2)};\n`,
  'utf8',
);

// Stamp the version into sw.js itself. A browser only checks for a new
// service worker by byte-comparing the *registered* script — changes to
// files it pulls in via importScripts() (sw-manifest.js) are invisible to
// that check on their own. This line is what actually makes an update fire.
const swSource = await readFile(SW_FILE, 'utf8');
const stamped = swSource.replace(
  /^\/\* build: mc-[0-9a-f]{10} \*\/\n/,
  '',
);
await writeFile(SW_FILE, `/* build: ${version} */\n${stamped}`, 'utf8');

console.log(`[precache] ${urls.length} urls · ${version}`);
