import type { BaseTerrain, Resource, TribeId, UnitKind } from '../game/types';
import type { ClimateTerrain } from './terrain';

export interface BiomePalette {
  field: string; // top colour of field tiles
  fieldSide: string;
  forest: string; // tree foliage
  trunk: string;
  mountain: string;
  mountainShade: string;
  snow: string;
  shallow: string;
  ocean: string;
}

/** The three empire types: each trains its own two role units (see game/roles). */
export type Category = 'military' | 'economy' | 'naval';

export interface TribeDef {
  id: TribeId;
  category: Category;
  name: string; // empire name
  people: string; // adjective / demonym
  color: string; // territory / banner colour
  colorDark: string;
  roof: string;
  startTech: string;
  unique: UnitKind;
  replaces: UnitKind; // the standard unit the unique unit stands in for
  bonus: string;
  blurb: string;
  terrain: Record<BaseTerrain, number>; // relative weights for land/water generation
  climate?: Partial<Record<ClimateTerrain, number>>; // share of this homeland's fields that are desert, swamp or tundra
  resources: Partial<Record<Resource, number>>; // spawn chance multipliers
  palette: BiomePalette;
  cityNames: string[];
}

